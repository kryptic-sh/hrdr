//! Generates the built-in command registry: one `(file stem, include_str! path)`
//! entry per `*.md` in `src/templates/commands/`, emitted to
//! `OUT_DIR/builtin_commands.rs` and pulled into `commands.rs` via `include!`.
//! Adding a built-in command is adding a file — no Rust wiring to touch.

use std::{env, fs, path::Path};

fn main() {
    let dir = Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap())
        .join("src")
        .join("templates")
        .join("commands");
    let out = Path::new(&env::var("OUT_DIR").unwrap()).join("builtin_commands.rs");

    // Rebuild when a command file is added, removed or edited. The directory
    // line covers additions/removals; the per-file lines cover edits.
    println!("cargo:rerun-if-changed={}", dir.display());

    // Failures are the build's to report, by name: a missing directory would
    // otherwise ship no built-in commands at all, and a lossy file name an
    // `include_str!` path that does not exist.
    let mut files: Vec<String> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("reading {}: {e}", dir.display()))
        .map(|entry| entry.unwrap_or_else(|e| panic!("reading {}: {e}", dir.display())))
        .filter(|e| e.path().extension().is_some_and(|x| x == "md"))
        .map(|e| {
            e.file_name()
                .into_string()
                .unwrap_or_else(|name| panic!("built-in command file name is not UTF-8: {name:?}"))
        })
        .collect();
    files.sort();

    let mut code = String::from("// Generated by build.rs — do not edit.\n");
    code.push_str("/// `(file stem, source)` for every built-in command template.\n");
    code.push_str("pub(crate) static COMMAND_FILES: &[(&str, &str)] = &[\n");
    for file in &files {
        let stem = file.strip_suffix(".md").unwrap_or(file);
        let path = dir.join(file);
        let path = path
            .to_str()
            .unwrap_or_else(|| panic!("command template path is not UTF-8: {}", path.display()));
        code.push_str(&format!("    ({stem:?}, include_str!({path:?})),\n"));
        println!("cargo:rerun-if-changed={path}");
    }
    code.push_str("];\n");

    fs::write(&out, code).expect("write OUT_DIR/builtin_commands.rs");
}
